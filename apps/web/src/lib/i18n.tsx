export type Locale = "es" | "en";
type Params = Record<string, string | number | null | undefined>;

const dictionaries: Record<Locale, Partial<Record<MessageKey, string>>> = { en, es };

export function translate(locale: Locale, key: string, params?: Params): string {
  const template = dictionaries[locale][key as MessageKey] ?? en[key as MessageKey] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ""));
}

type I18n = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, params?: Params) => string;
  /** Translates a backend error code, falling back to the server's message. */
  tError: (e: unknown) => string;
};

const I18nContext = createContext<I18n | null>(null);
const STORAGE_KEY = "pmd.locale";

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("es");

  useEffect(() => {
    try {
      const saved = window.localStorage.getItem(STORAGE_KEY);
      // Browser storage is only readable after hydration; reading it here avoids a hydration mismatch.
      // eslint-disable-next-line react-hooks/set-state-in-effect
      if (saved === "en" || saved === "es") setLocaleState(saved);
    } catch {
      // storage unavailable: keep the default
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch {
      // ignore
    }
  }, []);

  const value = useMemo<I18n>(() => {
    const t = (key: string, params?: Params) => translate(locale, key, params);
    const tError = (e: unknown) => {
      if (e && typeof e === "object" && "code" in e) {
        const code = String((e as { code: string }).code);
        const key = `errors.${code}`;
        const translated = translate(locale, key);
        if (translated !== key) return translated;
        if (code === "HTTP_403") return translate(locale, "errors.FORBIDDEN");
        const message = (e as { message?: string }).message;
        if (message) return message;
      }
      if (e instanceof TypeError) return translate(locale, "errors.network");
      return translate(locale, "errors.generic");
    };
    return { locale, setLocale, t, tError };
  }, [locale, setLocale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside <I18nProvider>");
  return ctx;
}
