/** Both dictionaries, for checks that every key and placeholder is translated. */
export const messages = { es, en };

type Params = Record<string, string | number | null | undefined>;

export function translate(locale: Locale, key: string, params?: Params): string {
  const dict: Partial<Record<MessageKey, string>> = locale === "en" ? en : es;
  const template = dict[key as MessageKey] ?? es[key as MessageKey] ?? key;
  return params ? template.replace(/\{(\w+)\}/g, (_, n: string) => String(params[n] ?? "")) : template;
}

type I18n = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, params?: Params) => string;
  tError: (e: unknown) => string;
};

const Ctx = createContext<I18n | null>(null);
const KEY = "pmd.locale";

function deviceLocale(): Locale {
  return getLocales()[0]?.languageCode === "en" ? "en" : "es";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(deviceLocale);

  useEffect(() => {
    AsyncStorage.getItem(KEY).then((v) => {
      if (v === "es" || v === "en") setLocaleState(v);
    });
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    void AsyncStorage.setItem(KEY, l);
  }, []);

  const value = useMemo<I18n>(() => {
    const t = (key: string, params?: Params) => translate(locale, key, params);
    const tError = (e: unknown) => {
      if (isNetworkError(e)) return translate(locale, "errors.network");
      if (e && typeof e === "object" && "code" in e) {
        const key = `errors.${String((e as { code: string }).code)}`;
        const tr = translate(locale, key);
        if (tr !== key) return tr;
        const message = (e as { message?: string }).message;
        if (message) return message;
      }
      return translate(locale, "errors.generic");
    };
    return { locale, setLocale, t, tError };
  }, [locale, setLocale]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n must be used inside <I18nProvider>");
  return ctx;
}
