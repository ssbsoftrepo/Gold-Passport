-- Hash-chained, append-only custody ledger (the "gold passport").
create table audit.ledger_entries (
    id              bigint generated by default as identity primary key,
    chain_key       varchar(120) not null,
    sequence        bigint       not null,
    event_type      varchar(80)  not null,
    aggregate_type  varchar(40)  not null,
    aggregate_id    uuid         not null,
    lot_id          uuid,
    actor_user_id   uuid,
    actor_role      varchar(20),
    occurred_at     timestamptz  not null,
    payload         text         not null,
    prev_hash       varchar(64)  not null,
    hash            varchar(64)  not null,
    recorded_at     timestamptz  not null,
    constraint ledger_chain_seq_uq unique (chain_key, sequence)
);
create index ledger_lot_idx on audit.ledger_entries (lot_id);

-- Defence in depth: the database refuses to modify or delete ledger rows. (The hash chain would
-- reveal tampering anyway, see HashChain.verify.) In production also grant the app role only
-- INSERT/SELECT on this table.
create function audit.prevent_ledger_mutation() returns trigger
    language plpgsql as
$$
begin
    raise exception 'audit.ledger_entries is append-only';
end;
$$;

create trigger ledger_append_only
    before update or delete on audit.ledger_entries
    for each row execute function audit.prevent_ledger_mutation();
